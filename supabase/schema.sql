CREATE TABLE IF NOT EXISTS "public"."categories" (
    "id" bigint NOT NULL,
    "user_id" "uuid" DEFAULT "auth"."uid"(),
    "name" "text" NOT NULL,
    "type" "text" NOT NULL,
    "created_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "is_default" boolean DEFAULT false,
    CONSTRAINT "categories_type_check" CHECK (("type" = ANY (ARRAY['INCOME'::"text", 'EXPENSE'::"text"]))),
    CONSTRAINT "categories_user_or_default" CHECK (((("is_default" = true) AND ("user_id" IS NULL)) OR (("is_default" = false) AND ("user_id" IS NOT NULL))))
);


